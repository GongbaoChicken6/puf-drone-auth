//============================================================================
// crc16_mcrf4xx.v -- CRC-16/MCRF4XX 校验核（MAVLink v2 帧校验用）
//----------------------------------------------------------------------------
// 算法与 external/c_library_v2/checksum.h 的 crc_accumulate() 位精确一致：
//   tmp = (crc[7:0] ^ byte);
//   tmp = tmp ^ (tmp << 4);
//   crc = (crc >> 8) ^ (tmp << 8) ^ (tmp << 3) ^ (tmp >> 4);
//
// 使用方法（三步一帧）：
//   1. 帧开始时 init 拉高 1 拍 —— 载入初值 16'hFFFF
//   2. 逐字节给 din + din_valid（每拍最多 1 字节）
//   3. 最后 1 字节累积完成后，crc 即为该帧 CRC 值（16-bit 原始值）
//
// 注意：帧尾存放为小端（低字节 crc[7:0] 在前），字节序由上层发送模块处理。
//
// 黄金向量（docs/protocol_contract.md §2）：
//   init 后吃入 8'hFD  ->  crc = 16'h23ED
//   init 后吃入 8'hAA  ->  crc = 16'h05D7
//============================================================================

module crc16_mcrf4xx (
    input  wire        clk       ,  // 时钟
    input  wire        rst       ,  // 同步复位，高有效
    input  wire        init      ,  // 帧起始脉冲：载入初值 16'hFFFF（1 拍）
    input  wire [7:0]  din       ,  // 串行字节输入
    input  wire        din_valid ,  // 字节有效，高电平 accumu 1 字节
    output wire [15:0] crc       ,  // 当前累积值（组合直出，随读随用）
    output wire        busy         // 已 init 且未复位（提示累积中）
);

    //------------------------------------------------------------------------
    // 内部寄存器（声明处赋初值 = 复位值，上电 GSR 加载，仿真无 x 态）
    //------------------------------------------------------------------------
    reg [15:0] crc_r = 16'hFFFF;  // CRC 累积寄存器
    reg        armed = 1'b0;     // init 之后才接受字节，防止上电垃圾累积

    //------------------------------------------------------------------------
    // 每字节迭代组合逻辑（位精确对应公式，无状态）
    //------------------------------------------------------------------------
    wire [7:0]  t1      = crc_r[7:0] ^ din;  // 低 8 位异或输入字节
    wire [7:0]  t2      = t1 ^ (t1 << 4);    // 左移 4 再异或（8-bit 截断）
    wire [15:0] crc_nxt = (crc_r >> 8)      // 右移 8（高位补 0）
                        ^ (t2 << 8)         // t2 提到高 8 位
                        ^ (t2 << 3)         // t2 左移 3（11-bit，不溢出）
                        ^ (t2 >> 4)         // t2 右移 4（4-bit 零扩展）
                        ;                   // 16-bit 异或即截断，与 & 0xFFFF 等价

    //------------------------------------------------------------------------
    // 时序逻辑：三优先级 —— 复位 > 帧初始化 > 正常累积
    //------------------------------------------------------------------------
    always @(posedge clk) begin
        if (rst) begin
            crc_r <= 16'hFFFF;        // 复位到初值
            armed <= 1'b0;
        end else if (init) begin
            crc_r <= 16'hFFFF;        // 新帧开始：重载初值
            armed <= 1'b1;
        end else if (din_valid && armed) begin
            crc_r <= crc_nxt;         // 每有效拍累积 1 字节
        end
        // init 与 din_valid 同拍时：init 优先（本帧首字节下一拍再给）
    end

    //------------------------------------------------------------------------
    // 输出
    //------------------------------------------------------------------------
    assign crc  = crc_r;
    assign busy = armed;

endmodule
