def parse_hwh_ips(hwh_path):
    """Minimal .hwh walk: fullname -> {base, high} (hex strings)."""
    root = ET.parse(hwh_path).getroot()
    ips = {}
    for mod in root.iter("MODULENODE"):
        fn = mod.find("FULLNAME")
        if fn is None or not fn.text:
            continue
        name = fn.text.strip().lstrip("/")
        base = mod.find("MEMRANGES/MEMRANGE/BASEVALUE")
        high = mod.find("MEMRANGES/MEMRANGE/HIGHVALUE")
        if base is not None and base.text:
            ips[name] = {"base": base.text.strip(),
                         "high": (high.text.strip()
                                  if high is not None and high.text else None)}
    return ips


def to_camel(name):
    return "".join(p.capitalize()
                   for p in name.replace("-", "_").split("_"))


def render_driver(ip, base, span, contract):
    regs = contract.get("registers", [])
    reg_lines, read_all, rw_regs = [], [], []
    for r in regs:
        name, off = r["name"], int(r.get("offset", 0))
        doc = r.get("doc", "")
        reg_lines.append(
            f"    # {name} @ +0x{off:X} ({r.get('access', 'rw')}, "
            f"{r.get('width', 32)}b) {doc}".rstrip())
        reg_lines.append(
            f"    def read_{name}(self):\n"
            f"        \"\"\"Read {name} (+0x{off:X}).\"\"\"\n"
            f"        return self.mmio.read(0x{off:X})")
        if r.get("access", "rw") == "rw":
            reg_lines.append(
                f"\n    def write_{name}(self, value):\n"
                f"        \"\"\"Write {name} (+0x{off:X}).\"\"\"\n"
                f"        self.mmio.write(0x{off:X}, int(value))")
            rw_regs.append((name, off))
        read_all.append(f"            \"{name}\": self.mmio.read(0x{off:X}),")

    op_lines = []
    for op in contract.get("operations", []):
        body = [f"        \"\"\"{op.get('doc', op['name'])}\"\"\""]
        for w in op.get("writes", []):
            body.append(f"        self.write_{w['reg']}({w['value']})")
        wd = op.get("wait_done")
        if wd:
            body += [
                "        import time",
                f"        deadline = time.time() + "
                f"{float(wd.get('timeout_ms', 100)) / 1000:.6f}",
                "        while True:",
                f"            v = self.read_{wd['reg']}()",
                f"            if (v >> {int(wd.get('bit', 1))}) & 1:",
                "                break",
                "            if time.time() > deadline:",
                f"                raise TimeoutError('{op['name']}: "
                f"done bit not set')",
                "            time.sleep(0.001)"]
        if not op.get("writes") and not wd:
            body.append("        raise NotImplementedError("
                        "'fill in this operation')")
        op_lines.append(f"    def {op['name']}(self):\n" + "\n".join(body))

    rw_init = "\n".join(f"        (\"{n}\", 0x{o:X})," for n, o in rw_regs)
    if not rw_init:
        rw_init = "        # (contract defines no RW registers)"
    return DRIVER_TEMPLATE.format(
        ip=ip, cls=to_camel(ip), base=base, span=span, rw_init=rw_init,
        reg_props="\n\n".join(reg_lines),
        ops=("\n".join(op_lines) + "\n\n") if op_lines else "",
        read_all="\n".join(read_all))


def main():
    ap = argparse.ArgumentParser(
        description="Generate PYNQ driver + pytest skeleton from contract")
    ap.add_argument("--hwh", help="overlay .hwh (for base addresses)")
    ap.add_argument("--contract", required=True)
    ap.add_argument("--ip", help="restrict to one IP from the contract")
    ap.add_argument("--out-dir", default="gen")
    ap.add_argument("--base-addr", help="override base address (hex)")
    ap.add_argument("--span", type=lambda x: int(x, 0), default=0x10000)
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--no-tests", action="store_true")
    args = ap.parse_args()

    with open(args.contract, encoding="utf-8") as f:
        contract = json.load(f)

    ips_from_hwh = parse_hwh_ips(args.hwh) if args.hwh else {}

    contracts = (contract["contracts"] if "contracts" in contract
                 else [contract])
    if args.ip:
        contracts = [c for c in contracts if c.get("ip") == args.ip]
    if not contracts:
        print("[ERROR] no matching contract")
        sys.exit(2)

    os.makedirs(args.out_dir, exist_ok=True)
    generated = []
    for c in contracts:
        ip = c["ip"]
        if not isinstance(ip, str) or not ip.isidentifier():
            print(f"[ERROR] bad ip name: {ip!r}")
            sys.exit(2)
        if ip not in ips_from_hwh and not args.base_addr:
            print(f"[WARN] {ip} not found in {args.hwh or '<no hwh>'}; "
                  f"base defaults to 0x0 - pass --base-addr or fix name")
        base = args.base_addr or ips_from_hwh.get(ip, {}).get("base", "0x0")
        if ip in ips_from_hwh:
            b = int(base, 16)
            h = int(ips_from_hwh[ip].get("high", hex(b + args.span - 1)), 16)
            span = h - b + 1
        else:
            span = args.span

        drv_path = os.path.join(args.out_dir, f"driver_{ip}.py")
        tst_path = os.path.join(args.out_dir, f"test_{ip}.py")
        outputs = [(drv_path, render_driver(ip, base, span, c))]
        if not args.no_tests:
            outputs.append((tst_path, TEST_TEMPLATE.format(
                ip=ip, cls=to_camel(ip), span=span,
                reg_names=[r["name"] for r in c.get("registers", [])])))
        for p, content in outputs:
            if os.path.exists(p) and not args.force:
                print(f"[SKIP] {p} exists (use --force)")
                continue
            with open(p, "w", encoding="utf-8") as f:
                f.write(content)
            print(f"[GEN ] {p}")
            generated.append(p)
    tests = [p for p in generated
             if os.path.basename(p).startswith("test_")]
    if tests:
        print("[DONE] next: pytest " + " ".join(tests))


if __name__ == "__main__":
    main()
