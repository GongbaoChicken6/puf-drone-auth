"""
gen_speck_vectors.py -- 生成 Speck64/96 测试向量（单源生成器）

用法：
    python scripts/gen_speck_vectors.py              # 生成到 sim/testvectors/
    python scripts/gen_speck_vectors.py --check      # 验证已提交文件是否最新

输出：
    sim/testvectors/speck_random.mem  -- 1000 组随机 (key, pt, ct)
        格式：每行 3 个 hex 字段，空格分隔（$readmemh 兼容）
        key: 24 hex chars (96 bit)
        pt:  16 hex chars (64 bit)
        ct:  16 hex chars (64 bit)
"""

import sys
import os
import random
import struct

# 导入项目 Speck 实现
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src", "python", "common"))
from speck import Speck6496

SEED = 20261006
NUM_RANDOM = 1000
OUT_DIR = os.path.join(os.path.dirname(__file__), "..", "sim", "testvectors")
OUT_FILE = os.path.join(OUT_DIR, "speck_random.mem")


def to_bus_key(key_bytes: bytes) -> int:
    """key bytes → 96-bit bus value {l1, l0, k0}"""
    k0 = struct.unpack("<I", key_bytes[0:4])[0]
    l0 = struct.unpack("<I", key_bytes[4:8])[0]
    l1 = struct.unpack("<I", key_bytes[8:12])[0]
    return (l1 << 64) | (l0 << 32) | k0


def to_bus_pt(pt_bytes: bytes) -> int:
    """pt bytes → 64-bit bus value {y, x}"""
    y = struct.unpack("<I", pt_bytes[0:4])[0]
    x = struct.unpack("<I", pt_bytes[4:8])[0]
    return (y << 32) | x


def generate():
    os.makedirs(OUT_DIR, exist_ok=True)
    rng = random.Random(SEED)

    lines = []
    lines.append(f"// Speck64/96 random test vectors (seed={SEED}, count={NUM_RANDOM})")
    lines.append(f"// Generated by gen_speck_vectors.py -- DO NOT EDIT MANUALLY")
    lines.append(f"// Format: key_24hex pt_16hex ct_16hex")

    for i in range(NUM_RANDOM):
        key = bytes(rng.randrange(256) for _ in range(12))
        pt = bytes(rng.randrange(256) for _ in range(8))
        ct = Speck6496(key).encrypt(pt)

        k_bus = to_bus_key(key)
        p_bus = to_bus_pt(pt)
        c_bus = to_bus_pt(ct)  # same packing: {y, x}

        lines.append(f"{k_bus:024x} {p_bus:016x} {c_bus:016x}")

    content = "\n".join(lines) + "\n"

    with open(OUT_FILE, "w") as f:
        f.write(content)

    print(f"Generated {NUM_RANDOM} vectors to {OUT_FILE}")
    return content


def check():
    if not os.path.exists(OUT_FILE):
        print(f"FAIL: {OUT_FILE} does not exist")
        return False

    expected = generate()
    with open(OUT_FILE, "r") as f:
        actual = f.read()

    if actual == expected:
        print(f"PASS: {OUT_FILE} is up to date")
        return True
    else:
        print(f"FAIL: {OUT_FILE} is stale (run gen_speck_vectors.py to regenerate)")
        return False


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(0 if check() else 1)
    else:
        generate()
